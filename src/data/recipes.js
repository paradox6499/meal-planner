export function forbiddenIngredientsFor(allergyIds) {
  const set = new Set();
  ALLERGENS.filter((a) => allergyIds.includes(a.id)).forEach((a) =>
    a.ingredients.forEach((i) => set.add(i))
  );
  return set;
}

export function recipeHasAllergen(recipe, forbiddenSet) {
  if (forbiddenSet.size === 0) return false;
  return recipe.ingr.some(([name]) => forbiddenSet.has(name));
}

// --- реальные цены (мост из ../grocery-budget) ---
//
// PRICES: { "куриное филе": { price, unit: "kg"|"l"|"pcs", price_per_unit, retailer, fetched_at }, ... }
// Формируется скриптом ../grocery-budget/scripts/export_prices.py, здесь
// просто статический JSON-импорт — если файла нет, сборка сломается, поэтому
// он закоммичен как {} по умолчанию (см. src/data/prices.json).
import PRICES from "./prices.json";

// recipe.ingr использует "бытовые" единицы (г/мл/шт на порцию), а цены в
// PRICES — за кг/л/шт (см. grocery_budget.models.Unit) — вот пересчёт между ними.
const INGR_UNIT_TO_PRICE_UNIT = {
  "г": ["kg", 1 / 1000],
  "мл": ["l", 1 / 1000],
  "шт": ["pcs", 1],
};

/** Пытается посчитать реальную стоимость рецепта (на 1 порцию) по PRICES.
 * Возвращает null, если хотя бы для одного ингредиента нет данных — тогда
 * вызывающий код должен откатиться на recipe.cost, а не показывать
 * наполовину реальную, наполовину оценочную сумму как единое число. */
export function recipeCostFromPrices(recipe, prices = PRICES) {
  let total = 0;
  for (const [name, amount, unit] of recipe.ingr) {
    const priceInfo = prices[name];
    const conv = INGR_UNIT_TO_PRICE_UNIT[unit];
    if (!priceInfo || !conv || priceInfo.price_per_unit == null) return null;
    const [priceUnit, factor] = conv;
    if (priceInfo.unit !== priceUnit) return null; // разные единицы — не рискуем считать
    total += amount * factor * priceInfo.price_per_unit;
  }
  return Math.round(total);
}

/** cost рецепта с учётом реальных цен, если они есть для ВСЕХ его
 * ингредиентов; иначе — прежний оценочный `recipe.cost`. Второй элемент
 * пары — флаг "это реальная цена или оценка", для честного отображения в UI.
 *
 * Рецепты из VkusVill MCP (см. src/lib/vkusvillRecipes.js) уже приходят с
 * посчитанной по-настоящему ценой и явным recipe.isRealPrice — им не нужен
 * повторный поиск по prices.json (который заточен под другие имена
 * ингредиентов, из grocery-budget) — просто уважаем их собственный флаг. */
export function effectiveRecipeCost(recipe, prices = PRICES) {
  if (recipe.isRealPrice !== undefined) return [recipe.cost, recipe.isRealPrice];
  const real = recipeCostFromPrices(recipe, prices);
  return real === null ? [recipe.cost, false] : [real, true];
}
