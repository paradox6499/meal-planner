// "Уже есть дома" — отмеченные пользователем продукты (крупы, мука, специи и
// т.п.), которые не нужно докупать в ТЕКУЩЕМ списке, потому что дома ещё
// остались с прошлой недели. Раньше каждая неделя считалась с нуля, как
// будто на кухне вообще ничего нет, даже то, что реалистично хватает на
// месяцы (соль, мука, специи) — жалоба в чате: "мы же не будем покупать
// новую упаковку муки каждую неделю".
//
// Хранится как единый набор названий ингредиентов ("что у меня сейчас есть
// дома") — простой, честный компромисс: не полноценный инвентарь с граммами
// и сроками годности (это отдельная, куда более сложная фича — нужно точно
// знать, сколько купили и сколько ушло на рецепт), а просто "отметил —
// значит есть, снял отметку — значит закончилось". Отметка ставится на
// экране списка покупок (ResultView, App.jsx) и переживает переход на
// следующую неделю: если ингредиент из этого набора снова попадёт в список
// покупок, он будет отмечен галочкой сразу, без необходимости искать и
// отмечать заново — самое частое действие (мука/сахар/специи почти каждую
// неделю) не нужно повторять руками.
const PANTRY_KEY = "sedim.pantryStaples.v1";

export function loadPantryStaples() {
  try {
    const raw = localStorage.getItem(PANTRY_KEY);
    if (!raw) return new Set();
    const arr = JSON.parse(raw);
    return new Set(Array.isArray(arr) ? arr.filter((n) => typeof n === "string") : []);
  } catch {
    return new Set();
  }
}

export function savePantryStaples(namesSet) {
  try {
    localStorage.setItem(PANTRY_KEY, JSON.stringify([...namesSet]));
  } catch {
    // приватный режим браузера / квота — молча не сохраняем, тот же принцип, что и у profile.js
  }
}
